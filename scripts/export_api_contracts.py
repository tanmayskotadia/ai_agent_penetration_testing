"""Deterministic OpenAPI and TypeScript schema types; no target/credential access."""

import argparse
import json
from pathlib import Path
from typing import Any

from aegistrace.api import create_app
from aegistrace.report_content import VaptReportContent
from aegistrace.settings import Settings


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return "ApiSchemas[" + json.dumps(schema["$ref"].split("/")[-1]) + "]"
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return "(" + " | ".join(ts_type(value) for value in schema["anyOf"]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties")
            return (
                "Record<string, " + (ts_type(extra) if isinstance(extra, dict) else "unknown") + ">"
            )
        required = set(schema.get("required", []))
        return (
            "{ "
            + "; ".join(
                json.dumps(name) + ("" if name in required else "?") + ": " + ts_type(value)
                for name, value in schema["properties"].items()
            )
            + " }"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    settings = Settings(
        _env_file=None,
        app_secret="schema-export-only-never-a-runtime-key",
        database_url="sqlite:///:memory:",
    )
    schema = create_app(settings).openapi()
    types = "// Generated by scripts/export_api_contracts.py; do not edit.\nexport interface ApiSchemas {\n"
    types += "\n".join(
        "  " + json.dumps(name) + ": " + ts_type(value) + ";"
        for name, value in sorted(schema["components"]["schemas"].items())
    )
    types += "\n}\n"
    for path, value in [
        (root / "schemas/openapi.json", json.dumps(schema, indent=2, sort_keys=True) + "\n"),
        (root / "frontend/src/generated/api.ts", types),
        (
            root / "schemas/report-content.json",
            json.dumps(VaptReportContent.model_json_schema(), indent=2, sort_keys=True) + "\n",
        ),
    ]:
        path.parent.mkdir(parents=True, exist_ok=True)
        expected = value.encode("utf-8")
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                raise SystemExit(f"API contract drift: {path.name}")
        else:
            path.write_bytes(expected)


if __name__ == "__main__":
    main()
